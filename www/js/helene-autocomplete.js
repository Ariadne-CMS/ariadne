var langTools = ace.require("ace/ext/language_tools");
var pinpCompleter = {
	getCompletions: function(editor, session, pos, prefix, callback) {
		if (!editor.getBehavioursEnabled()) {
			callback(null, []);
			return;
		}
		var line = session.getDocument().getLine(pos.row).substring(0, pos.column);
		var match;
		var has = function(object, key) {
			return Object.prototype.hasOwnProperty.call(object, key);
		};
		var startsWith = function(word, start) {
			return word.substring(0, start.length).toLowerCase() === start.toLowerCase();
		};
		var completeMethods = function(module, start) {
			if (!has(ARList, module)) {
				callback(null, []);
				return;
			}
			callback(null, ARList[module].filter(function(method) {
				return startsWith(method, start);
			}).map(function(method) {
				return {name: method + '()', value: method + '()', score: 1, meta: 'ar'};
			}));
		};
		if ((match = /\bar\(\s*(['"])([^'"]*)$/.exec(line))) {
			var modulePrefix = match[2];
			callback(null, Object.keys(ARList).filter(function(module) {
				return startsWith(module, modulePrefix);
			}).map(function(module) {
				// Ace replaces only its identifier prefix, not the preceding path.
				return {name: module, value: module.substring(modulePrefix.length - prefix.length), score: 1, meta: 'ar'};
			}));
		} else if ((match = /\bar\(\s*(['"])([^'"]+)\1\s*\)\s*->\s*([\w]*)$/.exec(line))) {
			completeMethods(match[2], match[3]);
		} else if ((match = /\bar::([\w]+)\(\s*\)\s*->\s*([\w]*)$/.exec(line))) {
			// ar::html(), ar::loader(), etc. are module-loading shortcuts.
			completeMethods(match[1], match[2]);
		} else if ((match = /\bar::([\w]*)$/.exec(line))) {
			callback(null, Object.keys(ariadneList).filter(function(word) {
				return word.indexOf('ar::') === 0 && startsWith(word.substring(4), match[1]);
			}).map(function(word) {
				return {name: word + '()', value: word.substring(4) + '()', score: 1, meta: 'ar::'};
			}));
		} else if ((match = /(?:\b|::|->)call\(\s*(['"])([^'"]*)$/.exec(line))) {
			var templatePrefix = match[2];
			callback(null, templateList.filter(function(template) {
				return template.substring(0, templatePrefix.length) === templatePrefix;
			}).map(function(template) {
				return {name: template, value: template.substring(templatePrefix.length - prefix.length), score: 1, meta: 'template'};
			}));
		} else if (prefix.length) {
			callback(null, Object.keys(ariadneList).filter(function(word) {
				return startsWith(word, prefix);
			}).map(function(word) {
				var info = ariadneList[word];
				var value = info.value || word + '()';
				return {name: value, value: value, score: 1, meta: info.type};
			}));
		} else {
			callback(null, []);
		}
	}
};
langTools.addCompleter(pinpCompleter);
